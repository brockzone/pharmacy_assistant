"""
Generate synthetic training images using text2image (Tesseract's official tool).

What this does:
- Takes the ground truth labels from the manifest (the words we want to recognize)
- Renders each one with multiple diverse fonts using text2image
- Each rendered image gets a matching .box file (auto-generated by text2image)
- tesseract lstm.train converts each image+box into a binary .lstmf file
- This gives us a proper, balanced, multi-font training set

Why not use the webcam photos directly for training:
- Tesseract's lstm.train needs text to be detectable by its layout engine
- Webcam photos have varying lighting/angle/background that confuse the layout engine
- The standard Tesseract fine-tuning workflow uses text2image for train/val data
- Webcam photos are used as the held-out TEST set (which is correct)
"""
import csv
import subprocess
import sys
import unicodedata
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
TRAINING_DIR = PROJECT_ROOT / "training"
TESSDATA_BEST = TRAINING_DIR / "tessdata_best"
SYSTEM_TESSDATA = Path("/usr/share/tesseract-ocr/4.00/tessdata")
FONTS_DIR = Path("/usr/share/fonts")
TRAIN_DIR = TRAINING_DIR / "train"
VAL_DIR = TRAINING_DIR / "val"
TRAIN_DIR.mkdir(exist_ok=True)
VAL_DIR.mkdir(exist_ok=True)

HELD_OUT_TEST_IDS = {"whatsapp_photo_amox", "whatsapp_photo_asp", "whatsapp_photo_para"}

# Training words: cover all our targets + variants + look-alikes + catalog names
# This is what text2image will render (one line per word/phrase)
TRAIN_WORDS = [
    "PARACETAMOL", "paracetamol", "Paracetamol",
    "ASPIRIN", "aspirin", "Aspirin",
    "AMOXICILLIN", "amoxicillin", "Amoxicillin",
    "AMOXICILLIN 250 mg", "PARACETAMOL 500 mg", "ASPIRIN 300 mg",
    "tablet", "capsule", "syrup", "500 mg", "250 mg", "300 mg",
]

VAL_WORDS = [
    "AMOXCILLIN", "Amoxcillin",
    "PARACETAMOL 120 mg", "aspirin tablet",
    "AMOXICILLIN capsule",
]

# Fonts to use: diverse mix covering print styles seen on medicine packaging
TRAIN_FONTS = [
    "Liberation Sans",
    "Liberation Sans Bold",
    "DejaVu Sans Bold",
    "FreeSans",
    "FreeSans Semi-Bold",
    "Ubuntu Bold",
    "Ubuntu",
    "Liberation Mono Bold",
]

VAL_FONTS = [
    "DejaVu Sans",
    "Liberation Serif Bold",
]


def write_text_file(words: list[str], path: Path) -> None:
    path.write_text("\n".join(words) + "\n", encoding="utf-8")


def run_text2image(
    text_file: Path,
    output_base: Path,
    font: str,
    ptsize: int = 36,
) -> list[Path]:
    """Run text2image to render text with given font. Returns list of .tif files."""
    result = subprocess.run(
        [
            "text2image",
            f"--fonts_dir={FONTS_DIR}",
            f"--font={font}",
            f"--text={text_file}",
            f"--outputbase={output_base}",
            f"--ptsize={ptsize}",
            "--resolution=300",
            "--xsize=2000",
            "--ysize=400",
            "--margin=50",
            "--degrade_image=true",
            "--exposure=0",
        ],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        print(f"  text2image FAILED for font '{font}':")
        print(f"    {result.stderr.strip()[:300]}")
        return []

    # text2image produces one or more <base>.tif + <base>.box files
    tif_files = list(output_base.parent.glob(f"{output_base.name}*.tif"))
    return tif_files


def tif_to_lstmf(tif_path: Path, tessdata: Path) -> Path | None:
    """Convert a text2image .tif + .box file into a .lstmf file for lstmtraining."""
    base = tif_path.with_suffix("")
    result = subprocess.run(
        [
            "tesseract",
            str(tif_path),
            str(base),
            "--tessdata-dir", str(tessdata),
            "-l", "eng",
            str(SYSTEM_TESSDATA / "configs" / "lstm.train"),
        ],
        capture_output=True, text=True,
        env={**__import__("os").environ, "TESSDATA_PREFIX": str(tessdata)},
    )
    lstmf = base.with_suffix(".lstmf")
    if lstmf.is_file():
        return lstmf
    print(f"  lstm.train FAILED for {tif_path.name}: {result.stderr.strip()[:200]}")
    return None


print("── Generating TRAIN .lstmf files via text2image ──")
write_text_file(TRAIN_WORDS, TRAIN_DIR / "train_words.txt")

train_lstmf = []
for i, font in enumerate(TRAIN_FONTS):
    font_safe = font.replace(" ", "_")
    output_base = TRAIN_DIR / f"synth_{i:02d}_{font_safe}"
    tif_files = run_text2image(TRAIN_DIR / "train_words.txt", output_base, font)
    for tif in tif_files:
        p = tif_to_lstmf(tif, TESSDATA_BEST)
        if p:
            train_lstmf.append(str(p))
            print(f"  OK  {p.name}  [{font}]")

print(f"\n── Generating VAL .lstmf files via text2image ──")
write_text_file(VAL_WORDS, VAL_DIR / "val_words.txt")

val_lstmf = []
for i, font in enumerate(VAL_FONTS):
    font_safe = font.replace(" ", "_")
    output_base = VAL_DIR / f"synth_{i:02d}_{font_safe}"
    tif_files = run_text2image(VAL_DIR / "val_words.txt", output_base, font)
    for tif in tif_files:
        p = tif_to_lstmf(tif, TESSDATA_BEST)
        if p:
            val_lstmf.append(str(p))
            print(f"  OK  {p.name}  [{font}]")

(TRAINING_DIR / "train_list.txt").write_text("\n".join(train_lstmf) + "\n", encoding="utf-8")
(TRAINING_DIR / "val_list.txt").write_text("\n".join(val_lstmf) + "\n", encoding="utf-8")

print(f"\nDone:")
print(f"  train_list.txt  : {len(train_lstmf)} .lstmf files from {len(TRAIN_FONTS)} fonts")
print(f"  val_list.txt    : {len(val_lstmf)} .lstmf files from {len(VAL_FONTS)} fonts")

if len(train_lstmf) < 2:
    print("\nERROR: Too few training files. Cannot proceed with lstmtraining.")
    sys.exit(1)
